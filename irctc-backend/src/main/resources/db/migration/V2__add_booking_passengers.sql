CREATE TABLE IF NOT EXISTS booking_passengers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    age INTEGER NOT NULL,
    gender VARCHAR(16) NOT NULL,
    booking_id BIGINT NOT NULL,
    CONSTRAINT ck_booking_passengers_age CHECK (age BETWEEN 0 AND 120),
    CONSTRAINT ck_booking_passengers_gender CHECK (gender IN ('MALE', 'FEMALE', 'OTHER')),
    CONSTRAINT fk_booking_passengers_booking
        FOREIGN KEY (booking_id) REFERENCES bookings (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_booking_passengers_booking_id ON booking_passengers (booking_id);
