CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    username VARCHAR(255) NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT uk_users_username UNIQUE (username)
);

CREATE TABLE IF NOT EXISTS trains (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination VARCHAR(255) NOT NULL,
    source VARCHAR(255) NOT NULL,
    total_seats INTEGER NOT NULL,
    train_name VARCHAR(255) NOT NULL,
    train_number VARCHAR(255) NOT NULL,
    CONSTRAINT uk_trains_train_number UNIQUE (train_number),
    CONSTRAINT ck_trains_total_seats_positive CHECK (total_seats > 0)
);

CREATE TABLE IF NOT EXISTS train_seat_availability (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    available_seats INTEGER NOT NULL,
    travel_date DATE NOT NULL,
    train_id BIGINT NOT NULL,
    CONSTRAINT uk_seat_availability_train_date UNIQUE (train_id, travel_date),
    CONSTRAINT ck_seat_availability_nonnegative CHECK (available_seats >= 0),
    CONSTRAINT fk_seat_availability_train FOREIGN KEY (train_id) REFERENCES trains (id)
);

CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at DATE NOT NULL DEFAULT CURRENT_DATE,
    seats_booked INTEGER NOT NULL,
    status VARCHAR(255) NOT NULL,
    travel_date DATE NOT NULL,
    train_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT ck_bookings_seats_positive CHECK (seats_booked > 0),
    CONSTRAINT ck_bookings_status CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    CONSTRAINT fk_bookings_train FOREIGN KEY (train_id) REFERENCES trains (id),
    CONSTRAINT fk_bookings_user FOREIGN KEY (user_id) REFERENCES users (id)
);

